import Foundation

/// Pure decision rules for the same-ID discovery refresh path
/// (`ExperienceRepository.mergeDiscovered`). Given the stored experience and
/// an incoming discovery value sharing its id, the policy decides whether to
/// insert, refresh (with a fully merged value), or skip — and every skip is
/// attributed to an explicit `SkipReason`.
///
/// The policy is deliberately side-effect free: all SwiftData work lives in
/// `ExperienceRepository`, which writes the merged value the policy returns.
/// It never hands raw incoming values to the persistence layer.
///
/// ## What may be refreshed
/// Only rows that are unambiguously machine-generated by the known Explore
/// pipelines — see `isMachineGenerated(_:)` for the exact criterion.
/// Manual/user-created rows, curated seed copy, and field-visit or
/// human-verified content are never overwritten (`isHumanProtected(_:)`), and
/// rows whose provenance cannot be classified either way are left untouched
/// rather than risked.
public enum DiscoveryRefreshPolicy {
    // MARK: - Known machine signatures

    /// Source attribution strings written verbatim by the machine generation
    /// pipelines (`AIService` Edge/direct synthesis, `AIService.skeletonExperience`,
    /// and `CityExperienceFetcher`). A stored row is recognized as
    /// machine-generated only when every one of its sources carries one of
    /// these exact attributions on a machine source type.
    public static let automaticSourceAttributions: Set<String> = [
        "© OpenStreetMap contributors",
        "© OpenStreetMap contributors + AI",
        "© OpenStreetMap contributors + Foursquare/Apple Maps + AI",
        "© AutoNavi (Amap)",
        "© AutoNavi (Amap) + AI",
        "Apple Maps",
    ]

    /// Confidence `reason` strings written verbatim by the same pipelines.
    public static let machineConfidenceReasons: Set<String> = [
        "AI-synthesized via Edge Function, unverified",
        "AI-synthesized from OpenStreetMap, unverified",
        "AI-synthesized from OpenStreetMap + Foursquare/Apple Maps signals",
        "OpenStreetMap entry, no AI enrichment",
        "Amap entry, no AI enrichment",
        "Apple Maps entry, no AI enrichment",
    ]

    /// Why a same-ID incoming experience left the stored row untouched.
    public enum SkipReason: String, Equatable {
        /// The stored row is manual/user-created, curated, field-visited, or
        /// human-verified — its content must never be overwritten silently.
        case invalidCoordinates
        case protectedManual
        /// Provenance is neither clearly machine-generated nor clearly human:
        /// unknown attributions, empty sources, unrecognized confidence, or an
        /// id outside the `exp_osm_` machine namespace. Fails closed.
        case ambiguousIdentity
        /// The incoming value is a machine skeleton (offline/quota fallback)
        /// and the stored row carries richer content it must not erase.
        case skeletonDowngrade
        /// The incoming value is older than the stored row; a stale batch must
        /// not regress fresher content.
        case staleIncoming
    }

    /// The action to take for one incoming discovery experience.
    public enum Decision: Equatable {
        /// No stored row with this id — insert the incoming value as-is.
        case insert(Experience)
        /// Refresh the stored row with the policy-merged value.
        case refresh(merged: Experience)
        /// Leave the stored row untouched for the given reason.
        case skip(SkipReason)
    }

    // MARK: - Decision

    /// Decide how one incoming discovery experience relates to the stored row
    /// with the same id (`existing == nil` means no row yet).
    ///
    /// Reject invalid coordinates or unproven incoming provenance, then protect
    /// human content and apply freshness/richness checks to machine content.
    public static func decision(existing: Experience?, incoming: Experience) -> Decision {
        let coordinates = incoming.location.coordinates
        guard coordinates.count == 2, coordinates.allSatisfy(\.isFinite),
              (-180...180).contains(coordinates[0]), (-90...90).contains(coordinates[1]) else {
            return .skip(.invalidCoordinates)
        }
        if let existing, isHumanProtected(existing) { return .skip(.protectedManual) }
        guard isMachineGenerated(incoming), !isHumanProtected(incoming) else { return .skip(.ambiguousIdentity) }
        guard let existing else { return .insert(incoming) }
        guard existing.id == incoming.id else { return .skip(.ambiguousIdentity) }
        guard isMachineGenerated(existing) else {
            return .skip(.ambiguousIdentity)
        }
        if isMachineSkeleton(incoming), hasRichContent(existing) {
            return .skip(.skeletonDowngrade)
        }
        if incoming.updatedAt < existing.updatedAt {
            return .skip(.staleIncoming)
        }
        return .refresh(merged: merge(existing: existing, incoming: incoming))
    }

    // MARK: - Provenance predicates

    /// True when the source is one of the known machine-pipeline attributions:
    /// a machine source type (`.user`/`.amap` as written by the OSM/Amap
    /// pipelines) carrying one of `automaticSourceAttributions` verbatim.
    public static func isAutomaticSource(_ source: InformationSource) -> Bool {
        guard let attribution = source.attribution else { return false }
        switch source.type {
        case .user, .amap:
            return automaticSourceAttributions.contains(attribution)
        default:
            return false
        }
    }

    /// True when a human created or verified the stored row's content, so no
    /// automatic refresh may ever overwrite it: user-created ids
    /// (`exp_user_`), curated seed copy, any `field_visit` source (human field
    /// verification), or any trusted verification in the confidence signals.
    public static func isHumanProtected(_ experience: Experience) -> Bool {
        if experience.isUserCreated { return true }
        if experience.isCuratedSeed { return true }
        if experience.sources.contains(where: { $0.type == .fieldVisit }) { return true }
        return experience.confidence.signals.trustedVerifications > 0
    }

    /// True when every provenance marker on the row is explained by the known
    /// machine-generation pipelines:
    ///   1. the id lives in the `exp_osm_` machine namespace;
    ///   2. sources are non-empty and **every** source carries a known
    ///      automatic attribution on a machine source type;
    ///   3. confidence has zero trusted verifications and is machine-grade:
    ///      either a known machine reason, or the structural machine signature
    ///      (level ≤ 1 with no attached real-world signals).
    ///
    /// Anything else — an unrecognized attribution, an empty source list, a
    /// non-OSM id, or confidence we cannot attribute to a machine pipeline —
    /// is *ambiguous*: we neither treat it as safe to rewrite nor as human
    /// work, and skip the refresh (`.ambiguousIdentity`).
    public static func isMachineGenerated(_ experience: Experience) -> Bool {
        guard experience.isFromOpenStreetMap else { return false }
        guard !experience.sources.isEmpty else { return false }
        guard experience.sources.allSatisfy(isAutomaticSource) else { return false }
        guard experience.confidence.signals.trustedVerifications == 0 else { return false }
        if machineConfidenceReasons.contains(experience.confidence.reason) { return true }
        return experience.confidence.level <= 1 && experience.confidence.signals.totalCount == 0
    }

    // MARK: - Richness predicates

    /// True for the offline/quota-fallback skeleton
    /// (`AIService.skeletonExperience`): no AI enrichment, an unassessed
    /// (zero) Solo Score, and no timing, guidance, or warning content.
    public static func isMachineSkeleton(_ experience: Experience) -> Bool {
        !experience.isAIEnriched
            && experience.soloScore.overall <= 0
            && experience.bestTimes.isEmpty
            && experience.howTo.isEmpty
            && experience.realInconveniences.isEmpty
    }

    /// True when the row carries content a skeleton must never erase: AI copy,
    /// an assessed Solo Score, timing/guidance/warnings, or highlights.
    public static func hasRichContent(_ experience: Experience) -> Bool {
        experience.isAIEnriched
            || experience.soloScore.overall > 0
            || !experience.bestTimes.isEmpty
            || !experience.howTo.isEmpty
            || !experience.realInconveniences.isEmpty
            || !experience.highlights.isEmpty
    }

    // MARK: - Merge

    /// Build the merged value a refresh writes over `existing`. Fresh
    /// machine-generated facts win where they are allowed to win; user and
    /// community evidence is always retained. Field rules:
    ///
    /// | Field | Rule |
    /// | --- | --- |
    /// | id, createdAt, stats, status, userTags | kept from `existing` |
    /// | title, oneLiner, whyItMatters | `incoming`, falling back to `existing` when empty |
    /// | category | `incoming` (`.hidden` never overwrites a known category) |
    /// | coordinates, cityCode, names, address | `incoming`, per-field fallback to `existing` |
    /// | rating / hours / price / website / phone | `incoming`; unknown clears old machine facts |
    /// | photoUrls | union — `existing` order first, then new `incoming` URLs |
    /// | bestTimes | `incoming` verbatim — an empty list clears stale unsupported windows |
    /// | durationMinutes | `incoming` |
    /// | howTo, realInconveniences, nearbyExperienceIds | `incoming`; empty clears old machine facts |
    /// | soloScore | `existing` when it has community evidence (`basedOnCount > 0`), else `incoming` |
    /// | sources | `incoming` plus retained human (non-automatic) `existing` sources |
    /// | confidence | `existing` when it carries real-world signals, else `incoming` |
    /// | categoryHighlights | `incoming` when non-empty, else `existing` |
    /// | updatedAt | `incoming` |
    public static func merge(existing: Experience, incoming: Experience) -> Experience {
        let retainedHighlights: [CategoryHighlight]?
        if let incomingHighlights = incoming.categoryHighlights, !incomingHighlights.isEmpty {
            retainedHighlights = incomingHighlights
        } else {
            retainedHighlights = existing.categoryHighlights
        }
        let retainedCategory: ExperienceCategory =
            incoming.category == .hidden && existing.category != .hidden ? existing.category : incoming.category
        return Experience(
            id: existing.id,
            title: incoming.title.isEmpty ? existing.title : incoming.title,
            oneLiner: incoming.oneLiner.isEmpty ? existing.oneLiner : incoming.oneLiner,
            whyItMatters: incoming.whyItMatters.isEmpty ? existing.whyItMatters : incoming.whyItMatters,
            category: retainedCategory,
            location: mergedLocation(existing: existing.location, incoming: incoming.location),
            bestTimes: incoming.bestTimes,
            durationMinutes: incoming.durationMinutes,
            howTo: incoming.howTo,
            realInconveniences: incoming.realInconveniences,
            soloScore: existing.soloScore.basedOnCount > 0 ? existing.soloScore : incoming.soloScore,
            sources: mergedSources(existing: existing, incoming: incoming),
            confidence: mergedConfidence(existing: existing, incoming: incoming),
            nearbyExperienceIds: incoming.nearbyExperienceIds,
            stats: existing.stats,
            status: existing.status,
            createdAt: existing.createdAt,
            updatedAt: incoming.updatedAt,
            userTags: existing.userTags ?? incoming.userTags,
            categoryHighlights: retainedHighlights
        )
    }

    // MARK: - Merge helpers

    /// A complete synthesis replaces machine facts, including unknown values.
    /// Skeleton downgrade is rejected before this merge; user photos survive.
    private static func mergedLocation(
        existing: ExperienceLocation,
        incoming: ExperienceLocation
    ) -> ExperienceLocation {
        return ExperienceLocation(
            coordinates: incoming.coordinates,
            cityCode: incoming.cityCode.isEmpty ? existing.cityCode : incoming.cityCode,
            addressHint: incoming.addressHint,
            placeNameLocal: incoming.placeNameLocal,
            placeNameRomanized: incoming.placeNameRomanized,
            rating: incoming.rating,
            openingHours: incoming.openingHours,
            priceLevel: incoming.priceLevel,
            website: incoming.website,
            phone: incoming.phone,
            photoUrls: mergedPhotoUrls(existing: existing.photoUrls, incoming: incoming.photoUrls)
        )
    }

    /// Photo union: existing URLs (including user-added "real" photos) keep
    /// their order and are never dropped; new incoming URLs are appended
    /// de-duplicated.
    private static func mergedPhotoUrls(existing: [String]?, incoming: [String]?) -> [String]? {
        guard existing != nil || incoming != nil else { return nil }
        var seen: Set<String> = []
        var merged: [String] = []
        for url in (existing ?? []) + (incoming ?? []) {
            if seen.insert(url).inserted {
                merged.append(url)
            }
        }
        return merged
    }

    /// Fresh automatic sources replace their stale automatic counterparts;
    /// any human (non-automatic) source on the stored row is trustworthy
    /// evidence and is always retained.
    private static func mergedSources(existing: Experience, incoming: Experience) -> [InformationSource] {
        var seen: Set<String> = []
        var merged: [InformationSource] = []
        let retained = existing.sources.filter { !isAutomaticSource($0) }
        for source in incoming.sources + retained {
            let key = "\(source.type.rawValue)|\(source.url?.absoluteString ?? "")|\(source.attribution ?? "")"
            if seen.insert(key).inserted {
                merged.append(source)
            }
        }
        return merged
    }

    /// Confidence carrying real-world signals (reports, GPS hits, trusted
    /// verifications) is human/community evidence and survives the refresh; a
    /// bare machine signature yields to the fresh one.
    private static func mergedConfidence(existing: Experience, incoming: Experience) -> Confidence {
        existing.confidence.signals.totalCount > 0 ? existing.confidence : incoming.confidence
    }
}

/// Outcome of `ExperienceRepository.mergeDiscovered(_:)`: which ids were newly
/// inserted, which stored rows were refreshed in place, and which were left
/// untouched with the policy reason. Callers use `insertedIDs` for new-only
/// badges/toasts and reload their visible state when `didChangeStore` is true.
public struct DiscoveryMergeResult: Equatable {
    /// Ids with no stored row that were inserted from the batch.
    public let insertedIDs: Set<String>
    /// Ids whose stored row was refreshed with merged content (count stays 1).
    public let refreshedIDs: Set<String>
    /// Ids left untouched, keyed by the policy reason for skipping.
    public let skipped: [String: DiscoveryRefreshPolicy.SkipReason]

    /// Number of newly inserted rows — the "new discoveries" count.
    public var insertedCount: Int { insertedIDs.count }

    /// Number of stored rows refreshed in place.
    public var refreshedCount: Int { refreshedIDs.count }

    /// True when the store changed (inserted or refreshed), i.e. when callers
    /// should reload their visible experiences.
    public var didChangeStore: Bool { !insertedIDs.isEmpty || !refreshedIDs.isEmpty }

    /// Build a result; empty sets are the natural default for a no-op batch.
    public init(
        insertedIDs: Set<String> = [],
        refreshedIDs: Set<String> = [],
        skipped: [String: DiscoveryRefreshPolicy.SkipReason] = [:]
    ) {
        self.insertedIDs = insertedIDs
        self.refreshedIDs = refreshedIDs
        self.skipped = skipped
    }
}
